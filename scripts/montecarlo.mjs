#!/usr/bin/env node
// Reproduces the handoff §5 Monte Carlo (exact two-hand optimum, no rerolls), adds a
// reroll-aware greedy-bot benchmark, checks category frequencies, and measures the
// level generator per tier. Usage: node scripts/montecarlo.mjs [--boards=100000]
// [--botBoards=3000] [--tierBoards=300] [--seed=20261030] [--table=spec_v03] [--out=path]

import { writeFileSync } from 'node:fs';
import { createRng } from '../src/engine/rng.js';
import { buildGeometry } from '../src/engine/geometry.js';
import { makeFastEvaluator } from '../src/engine/solver.js';
import { rollFaces, generateLevel, TIERS, MIN_TIER, MAX_TIER } from '../src/engine/levels.js';
import { playGreedyBot, playNaiveBot } from '../src/engine/bot.js';
import { classify, CATEGORY_OUTCOMES } from '../src/engine/scoring.js';

const args = Object.fromEntries(process.argv.slice(2).map((a) => { const [k, v] = a.replace(/^--/, '').split('='); return [k, v ?? true]; }));
const N = Number(args.boards ?? 100000);
const NB = Number(args.botBoards ?? 3000);
const NT = Number(args.tierBoards ?? 300);
const SEED = String(args.seed ?? '20261030');
const TABLE = String(args.table ?? 'spec_v03');
const BONUS = 8;
const ONLY = args.only ? String(args.only).toUpperCase() : 'ABC';
const lines = [];
const out = (s = '') => { lines.push(s); console.log(s); };

function summarize(values) {
  const sorted = [...values].sort((a, b) => a - b);
  const n = sorted.length;
  const mean = sorted.reduce((s, v) => s + v, 0) / n;
  const sd = Math.sqrt(sorted.reduce((s, v) => s + (v - mean) ** 2, 0) / Math.max(1, n - 1));
  const q = (p) => sorted[Math.min(n - 1, Math.floor(p * n))];
  const pGe = (x) => sorted.filter((v) => v >= x).length / n;
  return { n, mean, sd, ci95: 1.96 * sd / Math.sqrt(n), median: q(0.5), p10: q(0.1), p90: q(0.9), pGe };
}
const pct = (x) => `${(100 * x).toFixed(1)}%`;
const ciP = (p, n) => `±${(100 * 1.96 * Math.sqrt(p * (1 - p) / n)).toFixed(1)}`;

const t0 = Date.now();
const geometry = buildGeometry(BONUS);
const evaluator = makeFastEvaluator(geometry, TABLE, 2);

out(`# Dice Snake 3×3 — simulation report`);
out(`Generated by scripts/montecarlo.mjs · seed ${SEED} · table ${TABLE} · bonus cell ${BONUS} · ${new Date().toISOString()}`);
out();

// ---- Part A: exact optimum without rerolls (handoff §5 reproduction) ----
if (ONLY.includes('A')) {
  const rng = createRng(`${SEED}/partA`);
  const plain = new Array(N);
  const bonus = new Array(N);
  const catCounts = {};
  for (let i = 0; i < N; i++) {
    const faces = rollFaces(rng, BONUS);
    plain[i] = evaluator.maxNoBonus(faces);
    bonus[i] = evaluator.maxWithBonus(faces);
    const c = classify(faces.slice(0, 4));
    catCounts[c] = (catCounts[c] || 0) + 1;
  }
  const a = summarize(plain);
  const b = summarize(bonus);
  out(`## A. Exact two-hand optimum, zero rerolls, perfect player (${N.toLocaleString()} boards)`);
  out();
  out('| Metric | Without ×2 | With optimally used ×2 | Handoff §5 (no ×2 / ×2) |');
  out('|---|---|---|---|');
  out(`| Mean | ${a.mean.toFixed(2)} ± ${a.ci95.toFixed(2)} | ${b.mean.toFixed(2)} ± ${b.ci95.toFixed(2)} | ~12.0 / ~21.6 |`);
  out(`| Median | ${a.median} | ${b.median} | 12 / 22 |`);
  out(`| 10th percentile | ${a.p10} | ${b.p10} | 4 / 6 |`);
  out(`| 90th percentile | ${a.p90} | ${b.p90} | 20 / 32 |`);
  out(`| P(max ≥ 20) | ${pct(a.pGe(20))} ${ciP(a.pGe(20), N)} | ${pct(b.pGe(20))} ${ciP(b.pGe(20), N)} | ~11.9% / ~63.0% |`);
  out(`| P(max ≥ 30) | ${pct(a.pGe(30))} ${ciP(a.pGe(30), N)} | ${pct(b.pGe(30))} ${ciP(b.pGe(30), N)} | ~4.1% / ~35.5% |`);
  out(`| P(max = 0) | ${pct(a.pGe(0) - a.pGe(1))} | ${pct(b.pGe(0) - b.pGe(1))} | — |`);
  out();
  out(`Distribution of the no-reroll optimum with ×2 (P(max ≥ x)): ` + [6, 8, 10, 12, 14, 16, 20, 26].map((x) => `≥${x}: ${pct(b.pGe(x))}`).join(', '));
  out();
  out('### Category frequency check (first four dice of each board vs exact 6⁴ table)');
  out();
  out('| Category | Empirical | Exact |');
  out('|---|---|---|');
  for (const [cat, exact] of Object.entries(CATEGORY_OUTCOMES)) {
    out(`| ${cat} | ${pct((catCounts[cat] || 0) / N)} | ${pct(exact / 1296)} |`);
  }
  out();
}

// ---- Part B: reroll-aware greedy bot on fresh boards ----
if (ONLY.includes('B')) {
  const rng = createRng(`${SEED}/partB`);
  const scores = [];
  const naive = [];
  const base = [];
  let rerolls = 0;
  for (let i = 0; i < NB; i++) {
    const faces = rollFaces(rng, BONUS);
    const level = { seed: `partB/${i}`, levelIndex: i, tier: 3, bonusIndex: BONUS, faces, target: 1000, rerolls: 2, scoreTable: TABLE, bonusMultiplier: 2 };
    const res = playGreedyBot(level, { rng, samples: 24 });
    scores.push(res.score);
    naive.push(playNaiveBot(level, { rng }).score);
    base.push(evaluator.maxWithBonus(faces));
    rerolls += res.rerollsUsed;
  }
  const s = summarize(scores);
  const n = summarize(naive);
  const b0 = summarize(base);
  out(`## B. Two rerolls, unconditional fresh boards (${NB.toLocaleString()} boards): greedy lookahead bot vs naive "keep what scores" bot`);
  out();
  out(`Opening-roll optimum with ×2 on the same boards: mean ${b0.mean.toFixed(2)}.`);
  out(`Greedy bot: mean ${s.mean.toFixed(2)} ± ${s.ci95.toFixed(2)}, median ${s.median}, p10 ${s.p10}, p90 ${s.p90}, mean rerolls used ${(rerolls / NB).toFixed(2)}.`);
  out(`Naive bot: mean ${n.mean.toFixed(2)} ± ${n.ci95.toFixed(2)}, median ${n.median}, p10 ${n.p10}, p90 ${n.p90} (always uses both rerolls).`);
  out();
  out('| Target T | P(greedy ≥ T) | P(naive ≥ T) |');
  out('|---|---|---|');
  for (const T of [6, 8, 10, 12, 14, 16, 20, 22, 25, 30, 32, 35, 40, 45, 60]) out(`| ${T} | ${pct(s.pGe(T))} | ${pct(n.pGe(T))} |`);
  out();
}

// ---- Part C: generator per tier, baseline vs hold-cap experiment ----
if (ONLY.includes('C')) {
  out(`## C. Level generator per tier (${NT} levels per tier, greedy bot, samples=16)`);
  out();
  out('| Tier | Target | Band (lo–hi of no-reroll ×2 optimum) | Mean opening optimum ×2 | Fallbacks | Greedy win rate | Naive win rate | Greedy win rate, hold cap 3 | Naive win rate, hold cap 3 | Mean greedy score |');
  out('|---|---|---|---|---|---|---|---|---|---|');
  for (let tier = MIN_TIER; tier <= MAX_TIER; tier++) {
    const spec = TIERS[tier];
    const rng = createRng(`${SEED}/partC/${tier}`);
    let wins = 0;
    let winsCap = 0;
    let naiveWins = 0;
    let naiveWinsCap = 0;
    let fallbacks = 0;
    let sumOpt = 0;
    let sumScore = 0;
    const seen = new Set();
    let dup = 0;
    for (let i = 0; i < NT; i++) {
      const level = generateLevel({ runSeed: `${SEED}/tier${tier}/run${i}`, levelIndex: i, tier, scoreTable: TABLE });
      if (level.fallback) fallbacks++;
      sumOpt += level.bestNoRerollWithBonus;
      const key = level.faces.join('');
      if (seen.has(key)) dup++;
      seen.add(key);
      const res = playGreedyBot(level, { rng, samples: 16 });
      if (res.won) wins++;
      sumScore += res.score;
      const cap = playGreedyBot(level, { rng, samples: 16, config: { maxHolds: 3 } });
      if (cap.won) winsCap++;
      if (playNaiveBot(level, { rng }).won) naiveWins++;
      if (playNaiveBot(level, { rng, config: { maxHolds: 3 } }).won) naiveWinsCap++;
    }
    out(`| ${tier} | ${spec.target} | ${(spec.target * spec.lo).toFixed(1)}–${(spec.target * spec.hi).toFixed(1)} | ${(sumOpt / NT).toFixed(1)} | ${fallbacks}${dup ? ` (dup ${dup})` : ''} | ${pct(wins / NT)} ${ciP(wins / NT, NT)} | ${pct(naiveWins / NT)} ${ciP(naiveWins / NT, NT)} | ${pct(winsCap / NT)} | ${pct(naiveWinsCap / NT)} | ${(sumScore / NT).toFixed(1)} |`);
  }
  out();
}

out(`Runtime: ${((Date.now() - t0) / 1000).toFixed(1)} s`);
if (args.out) {
  writeFileSync(String(args.out), lines.join('\n') + '\n');
  console.log(`written ${args.out}`);
}
