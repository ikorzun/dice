#!/usr/bin/env node
// The lift of the combination upgrades (owner, 02.11.2026) -> src/engine/uplift3.js (generated):
// - UP_SHARES: each combination's share of the points the greedy bot scores on the tier levels;
// - UP_LIFT[L]: the mean score lift at level L of a sensible player, who has won every level before it (a missed
//   target ends the run, owner 03.11.2026), each win giving an offer of three combinations and the pick that adds
//   the most points.
// Usage: node scripts/upgrades3.mjs [--levels=200] [--runs=4000] [--seed=uplift-1]
import { writeFileSync } from 'node:fs';
import { createRng } from '../src/engine/rng.js';
import { generateAutoLevel } from '../src/engine/levels3.js';
import { playGreedyBot3 } from '../src/engine/bot3.js';
import { AUTO_MULT } from '../src/engine/hands.js';

const args = Object.fromEntries(process.argv.slice(2).map((a) => { const [k, v] = a.replace(/^--/, '').split('='); return [k, v ?? true]; }));
const N = Number(args.levels ?? 200);
const RUNS = Number(args.runs ?? 4000);
const SEED = String(args.seed ?? 'uplift-1');
const LEVELS = 60; // the run is endless (owner, 03.11.2026); run3.js goes on from the last step
const CATS = ['pair', 'two_pairs', 'small_straight', 'three_kind', 'full_house', 'straight', 'four_kind', 'five_kind'];

const points = Object.fromEntries(CATS.map((c) => [c, 0]));
const rng = createRng(`${SEED}/bot`);
for (let tier = 1; tier <= 5; tier++) {
  for (let k = 0; k < N; k++) {
    const level = generateAutoLevel({ runSeed: `${SEED}/t${tier}/r${k}`, levelIndex: tier + (k % 8), tier });
    for (const h of playGreedyBot3(level, { rng }).state.hands) points[h.category] += h.total;
  }
}
const total = Object.values(points).reduce((s, v) => s + v, 0);
const shares = Object.fromEntries(CATS.map((c) => [c, points[c] / total]));

const lift = (ups) => CATS.reduce((s, c) => s + shares[c] * ((AUTO_MULT[c] + (ups[c] || 0)) / AUTO_MULT[c]), 0);
const pick = (offer) => offer.reduce((a, b) => (shares[b] / AUTO_MULT[b] > shares[a] / AUTO_MULT[a] ? b : a));
const sums = new Array(LEVELS + 1).fill(0);
const runRng = createRng(`${SEED}/runs`);
for (let r = 0; r < RUNS; r++) {
  const ups = {};
  for (let L = 1; L <= LEVELS; L++) {
    sums[L] += lift(ups);
    const pool = CATS.slice();
    const offer = [0, 1, 2].map(() => pool.splice(runRng.int(pool.length), 1)[0]);
    const c = pick(offer);
    ups[c] = (ups[c] || 0) + 1;
  }
}
const curve = sums.map((s, L) => (L ? Math.round((s / RUNS) * 1000) / 1000 : 1));
const fmt = (o) => `{ ${Object.entries(o).map(([k, v]) => `${k}: ${v}`).join(', ')} }`;
const shareOut = Object.fromEntries(CATS.map((c) => [c, Math.round(shares[c] * 10000) / 10000]));
writeFileSync('src/engine/uplift3.js', `// GENERATED by scripts/upgrades3.mjs (${N} greedy levels per tier, ${RUNS} runs, seed ${SEED}) — do not edit by hand.
// UP_SHARES: each combination's share of the greedy bot's points on the tier levels. UP_LIFT[L]: the mean score
// lift at level L of a sensible upgrader who has won every level before it (index 0 unused).

export const UP_SHARES = Object.freeze(${fmt(shareOut)});
export const UP_LIFT = Object.freeze([${curve.join(', ')}]);
`);
console.log('shares', shareOut);
console.log('lift', curve.slice(1).map((v, i) => `L${i + 1} ${v}`).join(' · '));
console.log('written src/engine/uplift3.js');
